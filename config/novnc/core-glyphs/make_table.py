#!/usr/bin/env python3
"""Write config/novnc/core-glyphs.js from cursors captured by capture.sh.

CAPTURE_DIR holds glyphs.txt ("NAME INDEX KEYWORD" per line) and, per glyph,
NAME.json (the probe's summary) and NAME.rgba (R, G, B, A bytes). Each glyph
becomes rows of one character per pixel: "." transparent, "#" opaque black,
"W" opaque white. A core cursor glyph has only those three states, so any
other pixel means the capture is not a core glyph and is an error.

Usage: make_table.py CAPTURE_DIR OUT_FILE
"""

import json
import sys
from pathlib import Path

BLACK = (0, 0, 0, 255)
WHITE = (255, 255, 255, 255)

HEADER = """\
// Generated by config/novnc/core-glyphs/capture.sh from {image_note}; do not edit.
//
// X core cursor font glyphs that Openbox uses, as the VNC server sends them,
// each with the CSS cursor keyword the patched noVNC shows instead (see
// coreGlyphKeyword in cursor-keyword.js). Rows hold one character per pixel:
// "." transparent, "#" opaque black, "W" opaque white.

export const CORE_GLYPHS = """


def glyph_rows(rgba: bytes, width: int, height: int, name: str) -> list[str]:
    if len(rgba) != width * height * 4:
        raise ValueError(f"{name}: expected {width * height * 4} bytes, got {len(rgba)}")
    rows = []
    for y in range(height):
        row = ""
        for x in range(width):
            pixel = tuple(rgba[(y * width + x) * 4 : (y * width + x) * 4 + 4])
            if pixel[3] == 0:
                row += "."
            elif pixel == BLACK:
                row += "#"
            elif pixel == WHITE:
                row += "W"
            else:
                raise ValueError(f"{name}: pixel ({x},{y}) {pixel} is not a core glyph pixel")
        rows.append(row)
    return rows


def build_table(capture_dir: Path) -> list[dict]:
    table = []
    for line in (capture_dir / "glyphs.txt").read_text().splitlines():
        name, index, keyword = line.split()
        summary = json.loads((capture_dir / f"{name}.json").read_text())
        width, height = summary["w"], summary["h"]
        if width == 0 or height == 0:
            raise ValueError(f"{name}: the VNC server sent an empty cursor")
        rgba = (capture_dir / f"{name}.rgba").read_bytes()
        table.append(
            {
                "glyph": name,
                "index": int(index),
                "keyword": keyword,
                "w": width,
                "h": height,
                "hotx": summary["hotx"],
                "hoty": summary["hoty"],
                "rows": glyph_rows(rgba, width, height, name),
            }
        )
    return table


def render(table: list[dict], image_note: str) -> str:
    entries = []
    for glyph in table:
        rows = "".join(f"            '{row}',\n" for row in glyph["rows"])
        entries.append(
            "    {\n"
            f"        glyph: '{glyph['glyph']}', index: {glyph['index']}, "
            f"keyword: '{glyph['keyword']}',\n"
            f"        w: {glyph['w']}, h: {glyph['h']}, "
            f"hotx: {glyph['hotx']}, hoty: {glyph['hoty']},\n"
            "        rows: [\n"
            f"{rows}"
            "        ],\n"
            "    },\n"
        )
    return HEADER.format(image_note=image_note) + "[\n" + "".join(entries) + "];\n"


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    capture_dir, out_file = Path(argv[0]), Path(argv[1])
    image_note = (capture_dir / "image.txt").read_text().strip()
    out_file.write_text(render(build_table(capture_dir), image_note))
    print(f"wrote {out_file}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
