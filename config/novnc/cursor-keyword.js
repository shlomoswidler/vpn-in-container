/*
 * Recognizes remote cursors that stand for a CSS cursor keyword, so the
 * browser can show its own native cursor instead of an image of the remote
 * one (config/cursors/README.md in the vpn-in-container repo). Two kinds:
 *
 * Marker cursors from the "native-css" Xcursor theme
 * (config/cursors/generate_native_theme.py).
 *
 * Each cursor in that theme is a 1 pixel tall, fully opaque image:
 *   pixel 0: R,G,B = "css" (0x63, 0x73, 0x73)
 *   pixel 1: R = keyword length, G = 0, B = format version (1)
 *   pixel 2..: the CSS cursor keyword in ASCII, three characters per pixel
 *              (R, G, B), zero padded.
 *
 * X core cursor font glyphs that Openbox uses (core-glyphs.js, generated by
 * config/novnc/core-glyphs/capture.sh). Openbox has no Xcursor support, so
 * its cursors are these fixed 1-bit images.
 */

import { CORE_GLYPHS } from './core-glyphs.js';

const MAGIC = [0x63, 0x73, 0x73];
const FORMAT_VERSION = 1;
const HEADER_PIXELS = 2;
const CHARS_PER_PIXEL = 3;

// CSS cursor keywords the theme may name (CSS Basic User Interface Level 4).
// "auto" and "none" are excluded: the remote side never needs them.
export const NATIVE_KEYWORDS = new Set([
    'default', 'context-menu', 'help', 'pointer', 'progress', 'wait',
    'cell', 'crosshair', 'text', 'vertical-text', 'alias', 'copy', 'move',
    'no-drop', 'not-allowed', 'grab', 'grabbing', 'all-scroll',
    'col-resize', 'row-resize', 'n-resize', 'e-resize', 's-resize',
    'w-resize', 'ne-resize', 'nw-resize', 'se-resize', 'sw-resize',
    'ew-resize', 'ns-resize', 'nesw-resize', 'nwse-resize',
    'zoom-in', 'zoom-out',
]);

// Returns the CSS cursor keyword a marker cursor stands for, or null if the
// image is an ordinary cursor. rgba holds w * h pixels as R, G, B, A bytes.
export function decodeCursorKeyword(rgba, w, h) {
    if (h !== 1 || w <= HEADER_PIXELS || rgba.length !== w * 4) {
        return null;
    }
    for (let px = 0; px < w; px++) {
        if (rgba[px * 4 + 3] !== 255) {
            return null;
        }
    }
    for (let i = 0; i < MAGIC.length; i++) {
        if (rgba[i] !== MAGIC[i]) {
            return null;
        }
    }
    const length = rgba[4];
    if (rgba[5] !== 0 || rgba[6] !== FORMAT_VERSION ||
        w !== HEADER_PIXELS + Math.ceil(length / CHARS_PER_PIXEL)) {
        return null;
    }

    let keyword = '';
    for (let i = 0; i < length; i++) {
        const px = HEADER_PIXELS + Math.floor(i / CHARS_PER_PIXEL);
        keyword += String.fromCharCode(rgba[px * 4 + (i % CHARS_PER_PIXEL)]);
    }
    return NATIVE_KEYWORDS.has(keyword) ? keyword : null;
}

// Glyph pixels as core-glyphs.js writes them.
function glyphPixel(rgba, offset) {
    if (rgba[offset + 3] === 0) {
        return '.';
    }
    if (rgba[offset + 3] !== 255) {
        return '?';
    }
    const rgb = rgba[offset] + ',' + rgba[offset + 1] + ',' + rgba[offset + 2];
    if (rgb === '0,0,0') {
        return '#';
    }
    return rgb === '255,255,255' ? 'W' : '?';
}

// Returns the CSS cursor keyword for an Openbox core glyph (same size,
// hotspot and pixels as an entry in CORE_GLYPHS), or null.
export function coreGlyphKeyword(rgba, hotx, hoty, w, h) {
    if (rgba.length !== w * h * 4) {
        return null;
    }
    for (const glyph of CORE_GLYPHS) {
        if (glyph.w !== w || glyph.h !== h || glyph.hotx !== hotx || glyph.hoty !== hoty) {
            continue;
        }
        let matches = true;
        for (let y = 0; y < h && matches; y++) {
            const row = glyph.rows[y];
            for (let x = 0; x < w; x++) {
                if (glyphPixel(rgba, (y * w + x) * 4) !== row[x]) {
                    matches = false;
                    break;
                }
            }
        }
        if (matches) {
            return glyph.keyword;
        }
    }
    return null;
}

// Returns the CSS cursor keyword the browser should show natively for a
// remote cursor, or null to draw the image. Arguments as in Cursor.change().
export function nativeCursorKeyword(rgba, hotx, hoty, w, h) {
    return decodeCursorKeyword(rgba, w, h) ?? coreGlyphKeyword(rgba, hotx, hoty, w, h);
}
